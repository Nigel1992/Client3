void platform_poll_events(Client *c) {
    sceCtrlPeekBufferPositive(&pad, 1);

    if (!(last_pad.Buttons & PSP_CTRL_LEFT) && pad.Buttons & PSP_CTRL_LEFT) {
        key_pressed(c->shell, K_LEFT, -1);
    }

    if (!(last_pad.Buttons & PSP_CTRL_RIGHT) && pad.Buttons & PSP_CTRL_RIGHT) {
        key_pressed(c->shell, K_RIGHT, -1);
    }

    if (!(last_pad.Buttons & PSP_CTRL_UP) && pad.Buttons & PSP_CTRL_UP) {
        key_pressed(c->shell, K_UP, -1);
    }

    if (!(last_pad.Buttons & PSP_CTRL_DOWN) && pad.Buttons & PSP_CTRL_DOWN) {
        key_pressed(c->shell, K_DOWN, -1);
    }

    if (last_pad.Buttons & PSP_CTRL_LEFT && !(pad.Buttons & PSP_CTRL_LEFT)) {
        key_released(c->shell, K_LEFT, -1);
    }

    if (last_pad.Buttons & PSP_CTRL_RIGHT && !(pad.Buttons & PSP_CTRL_RIGHT)) {
        key_released(c->shell, K_RIGHT, -1);
    }

    if (last_pad.Buttons & PSP_CTRL_UP && !(pad.Buttons & PSP_CTRL_UP)) {
        key_released(c->shell, K_UP, -1);
    }

    if (last_pad.Buttons & PSP_CTRL_DOWN && !(pad.Buttons & PSP_CTRL_DOWN)) {
        key_released(c->shell, K_DOWN, -1);
    }

    bool ctrl_press = !(last_pad.Buttons & PSP_CTRL_TRIANGLE) && pad.Buttons & PSP_CTRL_TRIANGLE;
    bool ctrl_release = last_pad.Buttons & PSP_CTRL_TRIANGLE && !(pad.Buttons & PSP_CTRL_TRIANGLE);
    if (ctrl_press) {
        key_pressed(c->shell, K_CONTROL, -1);
    }

    if (ctrl_release) {
        key_released(c->shell, K_CONTROL, -1);
    }

    if (!(last_pad.Buttons & PSP_CTRL_SELECT) && pad.Buttons & PSP_CTRL_SELECT) {
        _Custom.show_performance = !_Custom.show_performance;
    }

    if (!(last_pad.Buttons & PSP_CTRL_SQUARE) && pad.Buttons & PSP_CTRL_SQUARE) {
        if (!c->ingame) {
            client_login(c, c->username, c->password, false);
        }
    }

    if (pad.Buttons & PSP_CTRL_LTRIGGER) {
        screen_offset_x = 0;
        screen_offset_y = 0;
        c->redraw_background = true;
    }

    if (pad.Lx != 128 || pad.Ly != 128) {
        c->redraw_background = true;

#define CURSOR_SENSITIVITY 20
        // The complete client canvas is scaled to the PSP screen, so viewport
        // panning is unnecessary. Holding R moves the pointer faster.
        int sensitivity = (pad.Buttons & PSP_CTRL_RTRIGGER) ? 10 : CURSOR_SENSITIVITY;
        cursor_x = MAX(0, MIN(cursor_x + (pad.Lx - 128) / sensitivity, SCREEN_WIDTH - 1));
        cursor_y = MAX(0, MIN(cursor_y + (pad.Ly - 128) / sensitivity, SCREEN_HEIGHT - 1));

        int x = cursor_x;
        int y = cursor_y;

        c->shell->idle_cycles = 0;
        c->shell->mouse_x = x;
        c->shell->mouse_y = y;

        if (_InputTracking.enabled) {
            inputtracking_mouse_moved(&_InputTracking, x, y);
        }
    }

    bool left_press = !(last_pad.Buttons & PSP_CTRL_CIRCLE) && pad.Buttons & PSP_CTRL_CIRCLE;
    bool right_press = !(last_pad.Buttons & PSP_CTRL_CROSS) && pad.Buttons & PSP_CTRL_CROSS;

    if (left_press || right_press) {
        int x = cursor_x;
        int y = cursor_y;

        c->shell->idle_cycles = 0;
        c->shell->mouse_click_x = x;
        c->shell->mouse_click_y = y;

        if (right_press) {
            c->shell->mouse_click_button = 2;
            c->shell->mouse_button = 2;
        } else {
            c->shell->mouse_click_button = 1;
            c->shell->mouse_button = 1;
        }

        if (_InputTracking.enabled) {
            inputtracking_mouse_pressed(&_InputTracking, x, y, right_press ? 1 : 0);
        }
    }

    bool left_release = last_pad.Buttons & PSP_CTRL_CIRCLE && !(pad.Buttons & PSP_CTRL_CIRCLE);
    bool right_release = last_pad.Buttons & PSP_CTRL_CROSS && !(pad.Buttons & PSP_CTRL_CROSS);

    if (left_release || right_release) {
        c->shell->idle_cycles = 0;
        c->shell->mouse_button = 0;

        if (_InputTracking.enabled) {
            inputtracking_mouse_released(&_InputTracking, right_release ? 1 : 0);
        }
    }

    last_pad = pad;
}
void platform_blit_surface(Surface *surface, int x, int y) {
    int logical_x0 = x + screen_offset_x;
    int logical_y0 = y + screen_offset_y;
    int logical_x1 = logical_x0 + surface->w;
    int logical_y1 = logical_y0 + surface->h;
    int dst_x0 = (int)((int64_t)logical_x0 * SCREEN_FB_WIDTH / SCREEN_WIDTH) - 1;
    int dst_y0 = (int)((int64_t)logical_y0 * SCREEN_FB_HEIGHT / SCREEN_HEIGHT) - 1;
    int dst_x1 = (int)(((int64_t)logical_x1 * SCREEN_FB_WIDTH + SCREEN_WIDTH - 1) / SCREEN_WIDTH) + 1;
    int dst_y1 = (int)(((int64_t)logical_y1 * SCREEN_FB_HEIGHT + SCREEN_HEIGHT - 1) / SCREEN_HEIGHT) + 1;

    if (dst_x0 < 0)
        dst_x0 = 0;
    if (dst_y0 < 0)
        dst_y0 = 0;
    if (dst_x1 > SCREEN_FB_WIDTH)
        dst_x1 = SCREEN_FB_WIDTH;
    if (dst_y1 > SCREEN_FB_HEIGHT)
        dst_y1 = SCREEN_FB_HEIGHT;

    int screen_cursor_x = cursor_x * SCREEN_FB_WIDTH / SCREEN_WIDTH;
    int screen_cursor_y = cursor_y * SCREEN_FB_HEIGHT / SCREEN_HEIGHT;
    int screen_cursor_w = MAX(1, CURSOR_W * SCREEN_FB_WIDTH / SCREEN_WIDTH);
    int screen_cursor_h = MAX(1, CURSOR_H * SCREEN_FB_HEIGHT / SCREEN_HEIGHT);

    for (int screen_y = dst_y0; screen_y < dst_y1; screen_y++) {
        int virtual_y = screen_y_to_logical[screen_y] - screen_offset_y;
        int row = virtual_y - y;
        if (row < 0 || row >= surface->h)
            continue;

        for (int screen_x = dst_x0; screen_x < dst_x1; screen_x++) {
            int virtual_x = screen_x_to_logical[screen_x] - screen_offset_x;
            int col = virtual_x - x;
            if (col < 0 || col >= surface->w)
                continue;

            int pixel = surface->pixels[row * surface->w + col];

            int cx = (screen_x - screen_cursor_x) * CURSOR_W / screen_cursor_w;
            int cy = (screen_y - screen_cursor_y) * CURSOR_H / screen_cursor_h;
            if (screen_x >= screen_cursor_x && screen_y >= screen_cursor_y && cx < CURSOR_W && cy < CURSOR_H) {
                int i = (cy * CURSOR_W + cx) * 4;
                uint8_t a = cursor[i + 3];
                if (a > 0) {
                    uint8_t r = cursor[i];
                    uint8_t g = cursor[i + 1];
                    uint8_t b = cursor[i + 2];
                    pixel = (r << 16) | (g << 8) | b;
                }
            }

            pixel = ((pixel & 0xff0000) >> 16) | (pixel & 0x00ff00) | ((pixel & 0x0000ff) << 16);
            fb[screen_y * VRAM_STRIDE + screen_x] = pixel;
        }
    }
    // sceDisplayWaitVblankStart();
    // sceDisplaySetFrameBuf(fb, VRAM_STRIDE, PSP_DISPLAY_PIXEL_FORMAT_8888, PSP_DISPLAY_SETBUF_NEXTFRAME);
}
